"""talks.json → src/online/StatueTalkTexts.ts (titles and transcripts shown while a talk plays). Run: python authoring/talks/make_ts.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
talks = json.load(open(os.path.join(HERE, 'talks.json'), encoding='utf-8'))
body = ',\n'.join(f" {json.dumps(t['id'])}:{{title:{json.dumps(t['title'],ensure_ascii=False)},text:{json.dumps(t['text'],ensure_ascii=False)}}}" for t in talks)
open(os.path.join(ROOT, 'src', 'online', 'StatueTalkTexts.ts'), 'w', encoding='utf-8').write(
 "// Generated by authoring/talks/make_ts.py from authoring/talks/talks.json — edit the JSON, not this file.\n"
 "export const TALK_TEXTS:Record<string,{title:string;text:string}>={\n" + body + "\n};\n")
print(len(talks), 'talks')
